export const getBibleBooks = (charset = 'simplified') =>
	BIBLE_BOOKS_DATA.map((book) => ({
		hanzi: charset === 'traditional' ? book.traditional : book.simplified,
		...book
	}));

export const getBibleBookOptions = (charset = 'simplified') =>
	getBibleBooks(charset).map((book) => book.hanzi);

export const findBookByName = (bookName) => {
	if (!bookName) return null;
	const normalized = bookName.trim();
	return (
		BIBLE_BOOKS_DATA.find(
			(book) => book.simplified === normalized || book.traditional === normalized
		) || null
	);
};

export const getBookInitialsForMethod = (book, inputMethod = 'pinyin') => {
	if (!book) return '';
	if (inputMethod === 'zhuyin') return book.zhuyinInitials;
	if (inputMethod === 'cangjie') return book.cangjieInitials;
	return book.initials;
};

export const getBookOrder = (bookName, charset = 'simplified') => {
	if (!bookName) return 999;
	const books = getBibleBooks(charset);
	const directIndex = books.findIndex((book) => book.hanzi === bookName);
	if (directIndex !== -1) return directIndex;

	const match = findBookByName(bookName);
	if (!match) return 999;
	const fallbackName = charset === 'traditional' ? match.traditional : match.simplified;
	const fallbackIndex = books.findIndex((book) => book.hanzi === fallbackName);
	return fallbackIndex !== -1 ? fallbackIndex : 999;
};

export const sortVersesByBibleOrder = (verses, charset = 'simplified') =>
	[...verses].sort((a, b) => {
		const bookOrderA = getBookOrder(a.bookName, charset);
		const bookOrderB = getBookOrder(b.bookName, charset);
		if (bookOrderA !== bookOrderB) return bookOrderA - bookOrderB;

		const chapterA = Number.parseInt(a.chapterNumber, 10) || 0;
		const chapterB = Number.parseInt(b.chapterNumber, 10) || 0;
		if (chapterA !== chapterB) return chapterA - chapterB;

		const verseA = Number.parseInt(a.verseNumber, 10) || 0;
		const verseB = Number.parseInt(b.verseNumber, 10) || 0;
		return verseA - verseB;
	});

/**
 * Creates a function to format verse references with Bible version when duplicates exist.
 * If multiple verses have the same reference (book, chapter, verse), the Bible version is appended.
 * @param {Array} verses - Array of verse objects to check for duplicates
 * @returns {Function} - Formatter function that takes a verse and returns formatted reference string
 */
export const createVerseReferenceFormatter = (verses) => {
	// Build a map of verse references to count occurrences
	const referenceMap = new Map();
	verses.forEach(verse => {
		const ref = `${verse.bookName}|${verse.chapterNumber}|${verse.verseNumber}`;
		referenceMap.set(ref, (referenceMap.get(ref) || 0) + 1);
	});

	// Return formatter function
	return (verse) => {
		const ref = `${verse.bookName}|${verse.chapterNumber}|${verse.verseNumber}`;
		const hasDuplicates = referenceMap.get(ref) > 1;
		
		const baseReference = `${verse.bookName} ${verse.chapterNumber}:${verse.verseNumber}`;
		
		if (hasDuplicates && verse.bibleVersion) {
			return `${baseReference} (${verse.bibleVersion})`;
		}
		
		return baseReference;
	};
};
